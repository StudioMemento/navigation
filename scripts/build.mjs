import {readFile,writeFile,mkdir,readdir,stat} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const output=path.join(root,'public'),source=path.join(root,'source','services');
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const text=file=>readFile(file,'utf8');
const report={date:'2026-10-28',checks:[],errors:[],files:0,bytes:0};
const check=(name,pass,detail)=>{report.checks.push({name,pass,detail});if(!pass)report.errors.push(name);};
const viewportScript=`<script>const tideViewport=()=>document.documentElement.style.setProperty('--tide-vh',innerHeight/100+'px');tideViewport();addEventListener('resize',tideViewport);if(parent!==window&&new URLSearchParams(location.search).has('sessionId')){const style=document.createElement('link');style.rel='stylesheet';style.href='/services/embed.css';document.head.append(style);}</script>`;

// Materialize only the adapter formerly generated by the local Node server.
// The original catalog and its provenance remain in source/services.
await mkdir(path.join(output,'services'),{recursive:true});
for(const entry of await readdir(source,{withFileTypes:true})){
  if(!entry.isFile()||!['.css','.js'].includes(path.extname(entry.name)))continue;
  let content=await text(path.join(source,entry.name));
  content=content.replaceAll('assets/','/services/assets/');
  if(entry.name.startsWith('catalogo')&&entry.name.endsWith('.css'))content=content.replace(/(-?\d*\.?\d+)(?:s|d|l)?vh\b/g,'calc(var(--tide-vh, 8px) * $1)');
  if(entry.name==='bridge.js')content=content.replace("  const origin=location.origin, stageId='s01_services';", "  if(parent===window||!sessionId){window.__TIDE_VISIBLE__=true;return;}\n  const origin=location.origin, stageId='s01_services';");
  await writeFile(path.join(output,'services',entry.name),content);
}
let html=await text(path.join(source,'original.html'));
html=html.replaceAll('assets/','/services/assets/').replaceAll('href="catalogo','href="/services/catalogo').replaceAll('src="catalogo','src="/services/catalogo');
html=html.replace('</head>',viewportScript+'<script src="/services/bridge.js" defer></script></head>');
await writeFile(path.join(output,'services','index.html'),html);

async function walk(folder){let result=[];for(const entry of await readdir(folder,{withFileTypes:true})){if(entry.isSymbolicLink())throw new Error('Symlinks are not permitted: '+entry.name);const file=path.join(folder,entry.name);result.push(...(entry.isDirectory()?await walk(file):[file]));}return result;}
const files=await walk(output);
for(const file of files){const bytes=await readFile(file),relative=path.relative(output,file).replaceAll('\\','/');report.files++;report.bytes+=bytes.length;
  if(file.endsWith('.json')){try{JSON.parse(bytes.toString('utf8').replace(/^\uFEFF/,''));}catch(error){check('JSON '+relative,false,error.message);}}
  if(file.endsWith('.glb'))check('GLB '+relative,bytes.readUInt32LE(0)===0x46546c67&&bytes.readUInt32LE(4)===2&&bytes.readUInt32LE(8)===bytes.length,{bytes:bytes.length});
}
const vendor=JSON.parse(await text(path.join(output,'vendor-lock.json')));
for(const row of vendor.files)check('Vendored '+row.path,sha(await readFile(path.join(output,row.path)))===row.sha256.toLowerCase());
const mediaFile=path.join(root,'reports','services_media_manifest.json');
// This manifest is also copied into licenses for Vercel builds that exclude QA reports.
const media=JSON.parse(await text(path.join(root,'licenses','services_media_manifest.json')).catch(()=>text(mediaFile)));
for(const row of media.files)check('Services media '+row.path,sha(await readFile(path.join(output,row.path.replace(/^\//,''))))===row.sha256);
check('Services media download complete',media.errors.length===0,{files:media.files.length,bytes:media.totalBytes});

async function resolves(url,base='/'){
  if(!url||/^(?:https?:|data:|mailto:|#|javascript:)/.test(url))return true;
  const parsed=new URL(url,'https://tide.local'+base);
  let target=path.join(output,decodeURIComponent(parsed.pathname));
  try{const info=await stat(target);if(info.isDirectory())target=path.join(target,'index.html');return(await stat(target)).isFile();}catch{return false;}
}
for(const name of ['index.html','services/index.html']){
  const content=await text(path.join(output,name));
  for(const match of content.matchAll(/(?:src|href)="([^"]+)"/g))check('HTML reference '+name+' '+match[1],await resolves(match[1],'/'+name));
}
for(const file of files.filter(file=>/\.(m?js)$/.test(file)&&!file.includes(path.sep+'services'+path.sep))){
  const content=await text(file),relative='/'+path.relative(output,file).replaceAll('\\','/');
  for(const match of content.matchAll(/(?:from\s*|import\s*\()(['"])(\.{1,2}\/[^'"\n]+)\1/g))check('Module reference '+relative+' '+match[2],await resolves(match[2],relative));
}
const navigation=JSON.parse(await text(path.join(output,'data','navigation.json')));
check('Six navigation stages',navigation.stages.length===6);
const config=JSON.parse(await text(path.join(root,'vercel.json')));
for(const row of navigation.stages.filter(row=>row.mode==='external')){
  const pathname='/'+row.id.replace(/^s\d+_/,'');
  check('Redirect matches '+row.id,config.redirects.some(redirect=>redirect.source===pathname&&redirect.destination===row.href));
}
check('Static-only Vercel output',config.framework===null&&config.outputDirectory==='public'&&!config.functions&&!config.builds);
await mkdir(path.join(root,'reports'),{recursive:true});
await writeFile(path.join(root,'reports','build.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({checks:report.checks.length,files:report.files,bytes:report.bytes,errors:report.errors}));
if(report.errors.length)process.exitCode=1;
