// START V27 navigation on the portfolio (as in LevelUp V20): one standalone bundle and first-paint shadow markup,
// generated from the 12.1.0 kit in site/navigation. No network, font or GPU dependency: the navbar is on screen with the
// first paint, before any module loads.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'site/navigation');
const { navMarkup } = await import(new URL('../site/navigation/render.mjs', import.meta.url));
const { syncNavViewport } = await import(new URL('../site/navigation/viewport.mjs', import.meta.url));
const PAGE = 'projects';
const embed = value => {
  const file = value.split('/').at(-1).split('?')[0];
  return 'data:image/webp;base64,' + readFileSync(resolve(dir, 'assets', file)).toString('base64');
};
const files = ['core', 'blur', 'styles', 'icon-assets', 'memento-paths', 'wordmark', 'icons', 'render', 'viewport', 'navbar', 'child'];
const parts = files.map(file => {
  let text = readFileSync(resolve(dir, file + '.mjs'), 'utf8');
  text = text.replace(/^import .+ from .+;\s*$/gm, '').replace(/^export /gm, '');
  text = text.replace(/new URL\('([^']+)',import.meta.url\).href/g, (_, path) => JSON.stringify(embed(path)));
  return '// navigation/' + file + '.mjs\n' + text;
});
writeFileSync(resolve(dir, 'portfolio.bundle.js'),
  '/* Generated by release/build-navigation.mjs. */\n(()=>{\n"use strict";\n' + parts.join('\n') +
  `\ninstallChild({page:${JSON.stringify(PAGE)},hub:"https://mementostudio.it"});\n})();\n`);
const markup = navMarkup(PAGE).replace(/file:[^"<>]+\/([^/"<>]+-nav.webp[^"<>]*)/g, (_, path) => embed(path));
const boot = `(()=>{const host=document.querySelector('memento-nav'),template=host.querySelector('template[shadowrootmode]');if(!host.shadowRoot&&template){host.attachShadow({mode:'open'}).append(template.content);template.remove();}(${syncNavViewport.toString()})(host);})();`;
const htmlFile = resolve(root, 'site/index.html');
let html = readFileSync(htmlFile, 'utf8');
const markers = /<!-- MEMENTO_OVERLAY_START -->[\s\S]*?<!-- MEMENTO_OVERLAY_END -->/;
if (!markers.test(html)) throw Error('site/index.html: navigation markers missing');
html = html.replace(markers, () =>
  `<!-- MEMENTO_OVERLAY_START -->\n<memento-nav active="${PAGE}" mode="standalone" hub="https://mementostudio.it" data-memento-kit="12.1.0" data-memento-prerender><template shadowrootmode="open">${markup}</template></memento-nav>\n<script>${boot}</script>\n<!-- MEMENTO_OVERLAY_END -->`);
writeFileSync(htmlFile, html);
console.log('Navigation bundle and first-paint markup synchronized (projects)');
