import { benefits } from '../src/content.js';
import { Carousel } from '../src/carousel.js';
import { benefitMarkup } from '../src/benefit-markup.js';
import { cp, mkdir, rm, readFile, writeFile, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname, join } from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const dist=join(root,'dist');
await rm(dist,{recursive:true,force:true}); await mkdir(dist,{recursive:true});
await cp(join(root,'public'),dist,{recursive:true,filter:source=>!source.endsWith('.prompt.txt')});
for(const name of ['index.html','styles.css','src']) await cp(join(root,name),join(dist,name),{recursive:true});
const content=await readFile(join(root,'src/content.js'),'utf8');
for(const m of content.matchAll(/asset: '([^']+)'/g)) await access(join(dist,m[1]));
const index=join(dist,'index.html');
let html=await readFile(index,'utf8');
const stage=/(<div\b[^>]*\bid="benefits"[^>]*>\s*<div class="carousel-stage">)(<\/div>)/;
if(!stage.test(html))throw new Error('Missing LevelUp benefit carousel');
html=html.replace(stage,(_,open,close)=>open+benefitMarkup()+close);
// Compute the resting layout with the same camera as the interactive carousel.
const count = benefits.length;
const at = (distance,wide) => Carousel.prototype.pose.call({fan:true,wide,width:1,height:1,stride:.78-.14*wide},distance);
const decimal = x => Math.round(x*10000)/10000;
const between = (a,b,unit) => `calc(${decimal(a)}${unit} + ${decimal(b-a)}${unit} * var(--layout-wide,0))`;
const initialBoards = Array.from({length:count},(_,i) => {
  const d=i>count/2?i-count:i;
  const a=at(d,0),b=at(d,1),edge=Math.min(2.7,count/2-.06);
  const transform=`translate3d(${between(-50+100*a.x,-50+100*b.x,'%')},${between(100*a.y,100*b.y,'%')},0) perspective(calc(1100px + 900px * var(--layout-wide,0))) rotateY(${between(a.yaw,b.yaw,'deg')}) scale(${decimal(a.scale)})`;
  return `#benefits .carousel-stage:not([data-positioned])>[data-slide="${i}"]{transform:${transform};visibility:${Math.abs(d)>=edge?'hidden':'visible'};opacity:${decimal(Math.max(0,Math.min(1,(edge-Math.abs(d))/.6)))};--slide-focus:${d===0?1:0};z-index:${100-20*Math.abs(d)}}`;
}).join('');
const firstPaint = `<style>${initialBoards}</style>`;
await writeFile(index,html.replace('</head>',firstPaint+'</head>'));
console.log('LEVELUP_BUILD_OK');
